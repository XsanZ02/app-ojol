CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(320) NOT NULL,
    phone_e164 VARCHAR(16),
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_full_name_not_blank CHECK (btrim(full_name) <> ''),
    CONSTRAINT users_email_valid CHECK (
        email = btrim(email) AND email ~ '^[^[:space:]@]+@[^[:space:]@]+$'
    ),
    CONSTRAINT users_phone_e164_format CHECK (
        phone_e164 IS NULL OR phone_e164 ~ '^\+[1-9][0-9]{0,14}$'
    ),
    CONSTRAINT users_password_hash_not_blank CHECK (btrim(password_hash) <> ''),
    CONSTRAINT users_status_valid CHECK (status IN ('active', 'suspended'))
);

CREATE UNIQUE INDEX users_email_lowercase_uq ON users (lower(email));
CREATE UNIQUE INDEX users_phone_e164_uq ON users (phone_e164) WHERE phone_e164 IS NOT NULL;

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT user_roles_pk PRIMARY KEY (user_id, role),
    CONSTRAINT user_roles_user_fk
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT user_roles_role_valid CHECK (role IN ('customer', 'driver'))
);

CREATE TABLE driver_profiles (
    user_id BIGINT PRIMARY KEY,
    role VARCHAR(16) NOT NULL DEFAULT 'driver',
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT driver_profiles_role_driver CHECK (role = 'driver'),
    CONSTRAINT driver_profiles_user_role_fk
        FOREIGN KEY (user_id, role) REFERENCES user_roles (user_id, role),
    CONSTRAINT driver_profiles_status_valid
        CHECK (status IN ('pending', 'active', 'suspended'))
);

CREATE INDEX driver_profiles_status_idx ON driver_profiles (status);

CREATE TABLE driver_vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_user_id BIGINT NOT NULL,
    vehicle_type VARCHAR(16) NOT NULL,
    plate_normalized VARCHAR(16) NOT NULL,
    make VARCHAR(80) NOT NULL,
    model VARCHAR(100) NOT NULL,
    color VARCHAR(40) NOT NULL,
    verification_status VARCHAR(16) NOT NULL DEFAULT 'pending',
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT driver_vehicles_driver_fk
        FOREIGN KEY (driver_user_id) REFERENCES driver_profiles (user_id),
    CONSTRAINT driver_vehicles_type_valid
        CHECK (vehicle_type IN ('motorcycle', 'car')),
    CONSTRAINT driver_vehicles_plate_normalized CHECK (
        plate_normalized = upper(plate_normalized)
        AND plate_normalized ~ '^[A-Z0-9]{4,16}$'
    ),
    CONSTRAINT driver_vehicles_make_not_blank CHECK (btrim(make) <> ''),
    CONSTRAINT driver_vehicles_model_not_blank CHECK (btrim(model) <> ''),
    CONSTRAINT driver_vehicles_color_not_blank CHECK (btrim(color) <> ''),
    CONSTRAINT driver_vehicles_verification_status_valid
        CHECK (verification_status IN ('pending', 'verified', 'rejected')),
    CONSTRAINT driver_vehicles_active_requires_verification
        CHECK (NOT is_active OR verification_status = 'verified'),
    CONSTRAINT driver_vehicles_owner_id_type_uq UNIQUE (driver_user_id, id, vehicle_type)
);

CREATE UNIQUE INDEX driver_vehicles_plate_uq ON driver_vehicles (plate_normalized);
CREATE INDEX driver_vehicles_active_driver_type_idx
    ON driver_vehicles (driver_user_id, vehicle_type)
    WHERE is_active AND verification_status = 'verified';

CREATE TABLE trips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rider_user_id BIGINT NOT NULL,
    driver_user_id BIGINT,
    vehicle_id BIGINT,
    vehicle_type VARCHAR(16) NOT NULL,
    pickup_address TEXT NOT NULL,
    pickup_latitude NUMERIC(9, 6) NOT NULL,
    pickup_longitude NUMERIC(9, 6) NOT NULL,
    dropoff_address TEXT NOT NULL,
    dropoff_latitude NUMERIC(9, 6) NOT NULL,
    dropoff_longitude NUMERIC(9, 6) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'requested',
    estimated_fare NUMERIC(12, 2) NOT NULL,
    final_fare NUMERIC(12, 2),
    currency_code VARCHAR(3) NOT NULL DEFAULT 'IDR',
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    accepted_at TIMESTAMPTZ,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT trips_rider_user_fk
        FOREIGN KEY (rider_user_id) REFERENCES users (id),
    CONSTRAINT trips_driver_vehicle_fk
        FOREIGN KEY (driver_user_id, vehicle_id, vehicle_type)
        REFERENCES driver_vehicles (driver_user_id, id, vehicle_type),
    CONSTRAINT trips_pickup_address_not_blank CHECK (btrim(pickup_address) <> ''),
    CONSTRAINT trips_dropoff_address_not_blank CHECK (btrim(dropoff_address) <> ''),
    CONSTRAINT trips_pickup_latitude_range CHECK (pickup_latitude BETWEEN -90 AND 90),
    CONSTRAINT trips_pickup_longitude_range CHECK (pickup_longitude BETWEEN -180 AND 180),
    CONSTRAINT trips_dropoff_latitude_range CHECK (dropoff_latitude BETWEEN -90 AND 90),
    CONSTRAINT trips_dropoff_longitude_range CHECK (dropoff_longitude BETWEEN -180 AND 180),
    CONSTRAINT trips_vehicle_type_valid CHECK (vehicle_type IN ('motorcycle', 'car')),
    CONSTRAINT trips_vehicle_assignment_complete CHECK (
        (driver_user_id IS NULL) = (vehicle_id IS NULL)
    ),
    CONSTRAINT trips_status_valid CHECK (
        status IN ('requested', 'accepted', 'picking_up', 'in_progress', 'completed', 'cancelled')
    ),
    CONSTRAINT trips_rider_driver_distinct CHECK (
        driver_user_id IS NULL OR rider_user_id <> driver_user_id
    ),
    CONSTRAINT trips_fare_nonnegative CHECK (
        estimated_fare >= 0 AND (final_fare IS NULL OR final_fare >= 0)
    ),
    CONSTRAINT trips_final_fare_only_when_completed CHECK (
        final_fare IS NULL OR status = 'completed'
    ),
    CONSTRAINT trips_currency_code_valid CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT trips_assignment_matches_acceptance CHECK (
        (driver_user_id IS NOT NULL) = (accepted_at IS NOT NULL)
    ),
    CONSTRAINT trips_status_timestamps_consistent CHECK (
        (status = 'requested'
            AND accepted_at IS NULL AND started_at IS NULL
            AND completed_at IS NULL AND cancelled_at IS NULL
            AND final_fare IS NULL)
        OR (status IN ('accepted', 'picking_up')
            AND driver_user_id IS NOT NULL AND accepted_at IS NOT NULL
            AND started_at IS NULL AND completed_at IS NULL
            AND cancelled_at IS NULL AND final_fare IS NULL)
        OR (status = 'in_progress'
            AND driver_user_id IS NOT NULL AND accepted_at IS NOT NULL
            AND started_at IS NOT NULL AND completed_at IS NULL
            AND cancelled_at IS NULL AND final_fare IS NULL)
        OR (status = 'completed'
            AND driver_user_id IS NOT NULL AND accepted_at IS NOT NULL
            AND started_at IS NOT NULL AND completed_at IS NOT NULL
            AND cancelled_at IS NULL AND final_fare IS NOT NULL)
        OR (status = 'cancelled'
            AND cancelled_at IS NOT NULL AND started_at IS NULL
            AND completed_at IS NULL AND final_fare IS NULL)
    ),
    CONSTRAINT trips_timestamps_chronological CHECK (
        (accepted_at IS NULL OR accepted_at >= requested_at)
        AND (started_at IS NULL OR (accepted_at IS NOT NULL AND started_at >= accepted_at))
        AND (completed_at IS NULL OR (started_at IS NOT NULL AND completed_at >= started_at))
        AND (cancelled_at IS NULL OR cancelled_at >= COALESCE(accepted_at, requested_at))
    )
);

CREATE INDEX trips_rider_requested_at_idx ON trips (rider_user_id, requested_at DESC);
CREATE INDEX trips_driver_requested_at_idx
    ON trips (driver_user_id, requested_at DESC)
    WHERE driver_user_id IS NOT NULL;
CREATE INDEX trips_status_requested_at_idx ON trips (status, requested_at);

CREATE TABLE trip_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL,
    previous_status VARCHAR(16),
    new_status VARCHAR(16) NOT NULL,
    actor_user_id BIGINT NOT NULL,
    reason TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT trip_status_history_trip_fk
        FOREIGN KEY (trip_id) REFERENCES trips (id),
    CONSTRAINT trip_status_history_actor_fk
        FOREIGN KEY (actor_user_id) REFERENCES users (id),
    CONSTRAINT trip_status_history_previous_valid CHECK (
        previous_status IS NULL
        OR previous_status IN ('requested', 'accepted', 'picking_up', 'in_progress', 'completed', 'cancelled')
    ),
    CONSTRAINT trip_status_history_new_valid CHECK (
        new_status IN ('requested', 'accepted', 'picking_up', 'in_progress', 'completed', 'cancelled')
    ),
    CONSTRAINT trip_status_history_reason_not_blank CHECK (
        reason IS NULL OR btrim(reason) <> ''
    )
);

CREATE INDEX trip_status_history_trip_changed_idx
    ON trip_status_history (trip_id, changed_at);

CREATE TABLE payments (
    trip_id BIGINT PRIMARY KEY,
    method VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    amount NUMERIC(12, 2) NOT NULL,
    currency_code VARCHAR(3) NOT NULL DEFAULT 'IDR',
    provider VARCHAR(80),
    provider_reference VARCHAR(160),
    paid_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT payments_trip_fk
        FOREIGN KEY (trip_id) REFERENCES trips (id),
    CONSTRAINT payments_method_valid CHECK (method IN ('cash', 'digital')),
    CONSTRAINT payments_status_valid CHECK (
        status IN ('pending', 'succeeded', 'failed', 'refunded')
    ),
    CONSTRAINT payments_amount_nonnegative CHECK (amount >= 0),
    CONSTRAINT payments_currency_code_valid CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT payments_provider_not_blank CHECK (
        provider IS NULL OR btrim(provider) <> ''
    ),
    CONSTRAINT payments_provider_reference_not_blank CHECK (
        provider_reference IS NULL OR btrim(provider_reference) <> ''
    ),
    CONSTRAINT payments_provider_reference_requires_provider CHECK (
        provider_reference IS NULL OR provider IS NOT NULL
    ),
    CONSTRAINT payments_paid_state_matches_timestamp CHECK (
        (status IN ('succeeded', 'refunded')) = (paid_at IS NOT NULL)
    ),
    CONSTRAINT payments_settled_digital_has_provider_reference CHECK (
        method <> 'digital'
        OR status NOT IN ('succeeded', 'failed', 'refunded')
        OR (provider IS NOT NULL AND provider_reference IS NOT NULL)
    ),
    CONSTRAINT payments_cash_has_no_provider CHECK (
        method <> 'cash' OR (provider IS NULL AND provider_reference IS NULL)
    )
);

CREATE UNIQUE INDEX payments_provider_reference_uq
    ON payments (provider, provider_reference)
    WHERE provider_reference IS NOT NULL;

CREATE TABLE ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL,
    from_user_id BIGINT NOT NULL,
    to_user_id BIGINT NOT NULL,
    score SMALLINT NOT NULL,
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ratings_trip_fk
        FOREIGN KEY (trip_id) REFERENCES trips (id),
    CONSTRAINT ratings_from_user_fk
        FOREIGN KEY (from_user_id) REFERENCES users (id),
    CONSTRAINT ratings_to_user_fk
        FOREIGN KEY (to_user_id) REFERENCES users (id),
    CONSTRAINT ratings_trip_from_user_uq UNIQUE (trip_id, from_user_id),
    CONSTRAINT ratings_users_distinct CHECK (from_user_id <> to_user_id),
    CONSTRAINT ratings_score_range CHECK (score BETWEEN 1 AND 5),
    CONSTRAINT ratings_comment_length CHECK (
        comment IS NULL OR length(comment) <= 1000
    )
);

COMMENT ON TABLE ratings IS
    'Service must allow a rating only when the trip is completed and from_user_id and to_user_id are the two distinct trip participants; authorize from_user_id against the authenticated caller.';

CREATE FUNCTION set_updated_at() RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := statement_timestamp();
    RETURN NEW;
END;
$$;

CREATE TRIGGER users_set_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER driver_profiles_set_updated_at
    BEFORE UPDATE ON driver_profiles
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER driver_vehicles_set_updated_at
    BEFORE UPDATE ON driver_vehicles
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trips_set_updated_at
    BEFORE UPDATE ON trips
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER payments_set_updated_at
    BEFORE UPDATE ON payments
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMENT ON COLUMN trips.status IS
    'Service transitions: requested -> accepted or cancelled; accepted -> picking_up or cancelled; picking_up -> in_progress or cancelled; in_progress -> completed. completed and cancelled are terminal. Validate actor authorization and perform each transition atomically.';
